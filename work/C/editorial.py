def polish(items, appendix=False):
    """Move footer prose to notes, then apply explicit copy edits to visible text."""
    edits = APPENDIX_EDITS if appendix else MAIN_EDITS
    for item in items:
        notes=[]
        body=item['body']
        for pattern in [r'<div class="scene-caption">(.*?)</div>', r'<p class="caveat">(.*?)</p>']:
            def retain(match):
                text=plain(match.group(1))
                if text:notes.append(text)
                return ''
            body=re.sub(pattern,retain,body,flags=re.S)
        if notes:
            item['editorial_notes']=notes
            item['condition']=' / '.join(filter(None,[item.get('condition',''),*notes]))
        for before,after in edits.get(item['title'],{}).items():
            assert before in body, (item['title'],before)
            body=body.replace(before,after)
        item['body']=body
        if not appendix and item['title'] in SPOKEN:
            item['spoken']=SPOKEN[item['title']]


