def clarify_terms(slides, appendix):
    for items, labels in [(slides, MAIN_LABELS), (appendix, APPENDIX_LABELS)]:
        for item in items:
            title = item['title']
            for before, after in labels.get(title, {}).items():
                item['body'] = item['body'].replace(before, after)
            if items is slides and title in CLEAR_NARRATION:
                item['spoken'] = CLEAR_NARRATION[title]
    # Keep the same audience-facing model names in the cue sheet.
    cue_labels = {
        '범용 F': '공개 자세 모델',
        '현장650장 E10': '현장 650장 모델',
        '기준 E10 유지': '현장 650장 모델 유지',
        '기본 RVGGA0 선정': '기본 외형 모델 선정',
    }
    for item in slides:
        item['quick_cues'] = [cue_labels.get(cue, cue) for cue in item['quick_cues']]
    # The source conditions keep model keys for traceability.
    renames = {
        '과거 F·NF 후보 비교': '공개·혼합 학습 비교',
        'FT·KD 비교': '전체 학습과 증류 비교',
        '외형 학습과 시험용 E': '외형 모델 학습 비교',
        'own9e 비교 조건': '추가 검출 모델 비교 조건',
    }
    for item in appendix:
        item['title'] = renames.get(item['title'], item['title'])
